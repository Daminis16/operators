#Arithmetic operators
print(2 + 3) #addition
print(5 - 2) #subtraction
print(4 * 3) #multiplication
print(10 / 2) #division
print(10 // 3) #floor division
print(2 ** 3) #exponentiation
print(10 % 3) #modulus

